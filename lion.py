print('Загружаю библиотеки...')  # проверяем старт скрипта
import docx  # подключаем библеотеку для ворда
import matplotlib.pyplot as plt  # для графиков

print('Читаю вордовский файл...')  # пишем что открываем документ
doc = docx.Document('lion.docx')  # открываем исходный файл

abzacy = [p.text for p in doc.paragraphs]  # берем текст каждого абзаца
full_text = ' '.join(abzacy)  # соединяем все через пробел
print('Текст прочитан! Всего символов:', len(full_text))  # показываем объем

print('Очищаю текст и считаю слова...')  # пишем про начало подсчета
znaki = '.,!?:;-—()«»"\'1234567890'  # список лишних символов
for z in znaki:  # идем по знакам
    full_text = full_text.replace(z, ' ')  # меняем знак на пробел

words = full_text.split()  # режем на слова (разная форма = разные слова)
total_words = len(words)  # всего слов
print('Найдено слов:', total_words)  # выводим сколько слов нашлось

word_counts = {}  # словарь для подсчета слов
for w in words:  # перебираем слова
    if w in word_counts:  # если слово уже было
        word_counts[w] += 1  # прибавляем единицу
    else:
        word_counts[w] = 1  # иначе записываем первый раз

# сортируем слова по убыванию частоты
sorted_words = sorted(word_counts.items(), key=lambda pair: list(pair).pop(), reverse=True)
print('Уникальных слов для таблицы:', len(sorted_words))  # смотрим размер будущей таблицы

print('Быстро формирую таблицу в Word...')  # пишем про создание файла
out_doc = docx.Document()  # создаем новый документ
table = out_doc.add_table(rows=len(sorted_words) + 1, cols=3)  # создаем таблицу сразу нужного размера
table.style = 'Table Grid'  # включаем границы ячеек

# собираем все тексты для всех ячеек в один плоский список (это работает мгновенно)
vse_znacheniya = ['Слово', 'Частота встречи, раз', 'Частота встречи в %']  # сначала шапка
for word, count in sorted_words:  # идем по отсортированным словам
    procent = round((count / total_words) * 100, 2)  # считаем процент
    vse_znacheniya.extend([str(word), str(count), str(procent)])  # кидаем в общий список

# заполняем все ячейки таблицы за один быстрый проход
for yacheika, tekst in zip(table._cells, vse_znacheniya):  # связываем ячейку и текст
    yacheika.text = tekst  # записываем текст в ячейку

out_doc.save('statistika_slov.docx')  # сохраняем готовый фаил
print('Готово! Таблица сохранена в файл statistika_slov.docx')  # подтверждаем сохранение

print('Рисую график по буквам...')  # переходим к буквам
rus_letters = 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'  # русский алфавит
letter_counts = {l: 0 for l in rus_letters}  # словарь для букв с нулями

for ch in full_text.lower():  # идем по тексту в нижнем регистре для букв
    if ch in letter_counts:  # если это русская буква
        letter_counts[ch] += 1  # плюсуем

plt.figure(figsize=(12, 6))  # размер окна
plt.bar(list(letter_counts.keys()), list(letter_counts.values()), color='skyblue', edgecolor='black')  # столбцы
plt.title('Частота встречаемости букв в тексте')  # заголовок
plt.xlabel('Буквы')  # подпись снизу
plt.ylabel('Сколько раз встретилась')  # подпись сбоку
plt.grid(axis='y', linestyle='--')  # сетка
plt.show()  # показываем гистограмму
